// Pruebas de integración y capturas en Chrome. Requiere Playwright y sharp solo para QA.
const { chromium } = require('playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const sharp = require('sharp');
const base = process.env.QA_URL || 'http://127.0.0.1:4180';
const out = 'docs/qa-emil-regression';
fs.mkdirSync(out, { recursive: true });
const errors = [];
const results = [];
(async () => {
 const browser = await chromium.launch({ channel: 'chrome', headless: true });
 const page = await browser.newPage({ viewport: { width:1440, height:900 } });
 page.on('pageerror', error => errors.push(error.message));
 page.on('response', response => { if (response.url().startsWith(base) && response.status() >= 400) errors.push(`${response.status()}: ${response.url()}`); });
 await page.goto(base, { waitUntil:'networkidle' });
 await page.evaluate(() => document.fonts.ready);
 await page.waitForTimeout(1000);
 assert.equal(await page.locator('h1').count(), 1);
 assert.equal(await page.locator('.intro-loader').count(), 0);
 assert.equal(await page.locator('.life-frame').count(), 4);
 assert((await page.locator('.credentials-numbers').textContent()).includes('+40.000'));
 assert.deepEqual(await page.locator('main>section').evaluateAll(els=>els.map(e=>e.dataset.homeSection)),['hero','equipo','credenciales','testimonios','carrusel','servicios','proceso','precios','preguntas','blog','newsletter']);
 assert.equal(await page.locator('.service-item').count(), 3);
 assert.equal(await page.locator('.extra-service,.complementary,.care-intro,.everyday').count(), 0);
 assert.equal(await page.locator('.faq-item').count(), 6);
 const logoRatio = await page.locator('.footer-brand img').evaluate(el => el.getBoundingClientRect().width / el.getBoundingClientRect().height);
 assert(Math.abs(logoRatio - 1080 / 327) < .02, 'El logo debe conservar su proporción original.');
 const invalidLinks = await page.locator('a[href^="#"]').evaluateAll(links => links.filter(a => !document.getElementById(a.hash.slice(1))).map(a => a.hash));
 assert.deepEqual(invalidLinks, []);
 const whatsapp = await page.locator('[data-whatsapp]').evaluateAll(links => links.map(a => ({ href:a.href, service:a.dataset.service })));
 assert(whatsapp.every(a => { const u = new URL(a.href); return u.hostname === 'wa.me' && u.pathname === '/56933965202' && u.searchParams.get('text').length > 30; }));
 results.push('Un H1, tres especialidades, seis FAQ, anclas válidas y WhatsApp configurado en todos los accesos.');
 await page.locator('#traumatologica summary').click();
 await page.waitForTimeout(150);
 assert(await page.locator('#traumatologica').evaluate(el => el.open));
 assert(!await page.locator('#respiratoria').evaluate(el => el.open));
 assert.equal(await page.locator('#diagram-caption').textContent(), 'Movimiento a tu propio ritmo.');
 await page.locator('#respiratoria summary').focus();
 await page.keyboard.press('Enter');
 await page.waitForTimeout(150);
 assert(await page.locator('#respiratoria').evaluate(el => el.open));
 await page.locator('.faq-item').last().locator('summary').focus();
 await page.keyboard.press('Enter');
 assert(await page.locator('.faq-item').last().evaluate(el => el.open));
 await page.locator('.faq-item').first().locator('summary').click();
 await page.locator('#review-next').click();
 assert.equal(await page.locator('#review-author').textContent(), 'Pamela Contreras Neira');
 await page.locator('#review-prev').click();
 assert.equal(await page.locator('#review-author').textContent(), 'Rodrigo García');
 await page.locator('.team-panel').nth(1).locator('.team-vertical').click();
 assert.equal(await page.locator('.team-panel').nth(1).getAttribute('aria-expanded'), 'true');
 await page.locator('.team-panel').first().locator('.team-vertical').click();
 results.push('Servicios y FAQ por teclado, carrusel y paneles del equipo operativos.');
 const process = await page.locator('.timeline-node').evaluateAll(nodes => nodes.map(el => el.getBoundingClientRect().top + scrollY + el.offsetHeight / 2 - innerHeight * .48 + 2));
 const gotoY = async y => { await page.evaluate(y => window.scrollTo({ top:y, behavior:'instant' }), y); await page.waitForTimeout(250); };
 await gotoY(process[0]);
 const stepStart = await page.locator('.process-step.is-active h3').textContent();
 await gotoY(process.at(-1));
 const stepEnd = await page.locator('.process-step.is-active h3').textContent();
 assert.notEqual(stepStart, stepEnd);
 await gotoY(process[0]);
 assert.equal(await page.locator('.process-step.is-active h3').textContent(), stepStart);
 const story = await page.locator('.life-story').evaluate(el => ({ top:el.offsetTop, travel:el.offsetHeight-innerHeight }));
 await gotoY(story.top);
 assert(Number(await page.locator('.life-frame').first().evaluate(el=>getComputedStyle(el).opacity))<.01);
 assert(Number(await page.locator('.word-bold').first().evaluate(el=>getComputedStyle(el).opacity))<.05);
 await page.waitForTimeout(2200);
 assert(Number(await page.locator('.word-bold').last().evaluate(el=>getComputedStyle(el).opacity))>.95);
 const sceneScreens = [];
 for (const p of [0,.2,.45,.65,.82,1]) {
  await gotoY(story.top + story.travel*p);
  const file = `${out}/life-${Math.round(p*100)}.jpg`;
  await page.screenshot({ path:file, quality:78 });
  sceneScreens.push(file);
 }
 const finalFrame = await page.locator('.life-frame-last').boundingBox();
 assert(Math.abs(finalFrame.x) < 3 && Math.abs(finalFrame.width - 1440) < 3 && Math.abs(finalFrame.height - 900) < 3, JSON.stringify(finalFrame));
 await gotoY(story.top + story.travel*.2);
 assert(Number(await page.locator('.life-frame-last').evaluate(el => getComputedStyle(el).opacity)) < .1);
 await gotoY(story.top + story.travel*.78);
 assert(Number(await page.locator('.life-end').evaluate(el=>getComputedStyle(el).opacity))>.95);
 results.push('La línea de tiempo y la galería se pueden avanzar y retroceder; la última imagen llena el viewport.');
 const sectionSelectors = ['.hero','.team','.credentials','.testimonials','.life-story','.specialties','.process','.evaluation','.faq','.blog','.newsletter','.site-footer'];
 for (const [name,width,height] of [['desktop',1440,900],['tablet',768,1024],['mobile',390,844],['small',320,740]]) {
  await page.setViewportSize({ width,height });
  await gotoY(0);
  await page.waitForTimeout(300);
  const overflow = await page.evaluate(() => ({ width:innerWidth, scroll:document.documentElement.scrollWidth }));
  assert(overflow.scroll <= width+1, `${name} overflow: ${JSON.stringify(overflow)}`);
  await page.screenshot({ path:`${out}/${name}-hero.jpg`, quality:85 });
  if (name === 'desktop' || name === 'mobile') {
   const files = [];
   for (const [i, selector] of sectionSelectors.entries()) {
    const box = await page.locator(selector).evaluate(el => ({ top:el.getBoundingClientRect().top+scrollY, height:el.offsetHeight }));
    await gotoY(Math.max(0,box.top));
    await page.waitForTimeout(600);
    const file = `${out}/${name}-${i}.jpg`;
    await page.screenshot({ path:file, quality:78 });
    files.push(file);
   }
   const thumbs = await Promise.all(files.map(async (file,i) => ({ input:await sharp(file).resize({ width:360 }).jpeg().toBuffer(), top:Math.floor(i/3)*(Math.round(height*360/width)+15), left:i%3*360 })));
   await sharp({ create:{ width:1080, height:Math.ceil(files.length/3)*(Math.round(height*360/width)+15), channels:3, background:'#b8bfb1' } }).composite(thumbs).jpeg({quality:85}).toFile(`${out}/${name}-overview.jpg`);
  }
 }
 await page.setViewportSize({ width:390,height:844 });
 await gotoY(0);
 await page.locator('.menu-toggle').click();
 assert.equal(await page.locator('.menu-toggle').getAttribute('aria-expanded'),'true');
 await page.keyboard.press('Escape');
 assert(await page.locator('#mobile-menu').evaluate(el => el.hidden));
 assert(await page.locator('.menu-toggle').evaluate(el => el === document.activeElement));
 await page.locator('.menu-toggle').click();
 await page.locator('#mobile-menu a').first().click();
 assert(await page.locator('#mobile-menu').evaluate(el => el.hidden));
 results.push('Sin desbordamiento a 1440, 768, 390 y 320 px. Menú móvil por teclado y enlaces funcional.');
 const reduced = await browser.newPage({ viewport:{width:1440,height:900}, reducedMotion:'reduce' });
 await reduced.goto(base,{waitUntil:'networkidle'});
 assert(!await reduced.locator('html').evaluate(el => el.classList.contains('motion-enabled')));
 assert.equal(await reduced.locator('.intro-loader').count(),0);
 assert.equal(await reduced.locator('#pain-current').textContent(),'2');
 assert.equal(await reduced.locator('.timeline-card').count(),4);
 assert(await reduced.locator('.timeline-card').evaluateAll(els => els.every(el => getComputedStyle(el).transform === 'none')));
 await reduced.screenshot({path:`${out}/reduced-full.jpg`,fullPage:true,quality:70});
 const nojs = await browser.newPage({javaScriptEnabled:false,viewport:{width:390,height:844}});
 await nojs.goto(base,{waitUntil:'networkidle'});
 assert.equal(await nojs.locator('.service-item').count(),3);
 assert.equal(await nojs.locator('.faq-item').count(),6);
 assert((await nojs.locator('.hero-actions [data-whatsapp]').getAttribute('href')).includes('?text='));
 results.push('Movimiento reducido sin escenas fijadas ni loader. Contenido y WhatsApp disponibles sin JavaScript.');
 assert.deepEqual(errors, []);
 results.push('Sin errores JavaScript ni recursos locales fallidos.');
 fs.writeFileSync(`${out}/results.json`,JSON.stringify({date:new Date().toISOString(),results,errors},null,2));
 console.log(results.map(result => `PASS: ${result}`).join('\n'));
 await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
